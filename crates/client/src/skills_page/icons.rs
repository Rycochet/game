/// Where a skill's icon is, in the assets: its own, or the nearest above it.
pub(super) fn icon_path(id: SkillId) -> Option<String> {
    id.upwards().find_map(|node| {
        ICONS
            .iter()
            .find(|(path, _)| *path == node.path())
            .map(|(_, icon)| format!("icons/{icon}.png"))
    })
}

